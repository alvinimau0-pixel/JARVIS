"""Runtime configuration. Values come from environment variables prefixed ``JARVIS_``.

Secrets (session token, database password) are never given defaults and are never logged.
"""

from __future__ import annotations

import logging
import os
import secrets
from functools import lru_cache
from pathlib import Path
from typing import Annotated

from pydantic import Field, SecretStr, field_validator
from pydantic_settings import BaseSettings, NoDecode, SettingsConfigDict

from jarvis.secrets.store import KeyringStore, SecretStore

log = logging.getLogger("jarvis.config")
AUDIT_KEY_SECRET = "audit_hmac_key"  # noqa: S105 - a credential-store entry name


def _split_csv(value: object) -> object:
    if isinstance(value, str):
        return [item.strip() for item in value.split(",") if item.strip()]
    return value


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="JARVIS_", extra="ignore")

    # Per-launch token generated by the desktop shell (Tauri). Required: there is no default.
    session_token: SecretStr = Field(min_length=32)

    database_url: SecretStr

    # HMAC key for the audit chain. Loaded from the OS credential store (generated there on
    # first start) unless JARVIS_AUDIT_KEY is set. ``create_app`` refuses to start without it.
    audit_key: SecretStr | None = Field(default=None, min_length=32)
    audit_anchor_interval_seconds: float = Field(default=60.0, gt=0)

    host: str = "127.0.0.1"
    port: int = 8765

    # Browser origins allowed to call the API (Tauri webview + local dev server).
    allowed_origins: Annotated[list[str], NoDecode] = Field(
        default_factory=lambda: [
            "tauri://localhost",
            "http://tauri.localhost",
            "http://localhost:1420",
            "http://127.0.0.1:1420",
        ]
    )

    # Approved workspaces for L0/L1 operations. Anything outside requires approval or is denied.
    workspaces: Annotated[list[Path], NoDecode] = Field(default_factory=list)

    data_dir: Path = Path.home() / ".jarvis"

    approval_ttl_seconds: int = 600
    exec_default_timeout_seconds: float = 120.0
    exec_max_timeout_seconds: float = 1800.0
    exec_output_limit_bytes: int = 256 * 1024
    rate_limit_per_minute: int = 120
    exec_max_concurrent_jobs: int = Field(default=4, ge=1, le=64)
    # PID of the desktop shell. If set, the backend shuts down when that process disappears,
    # so closing (or crashing) the app never leaves an authenticated backend running.
    parent_pid: int | None = None

    @field_validator("allowed_origins", mode="before")
    @classmethod
    def _origins(cls, value: object) -> object:
        return _split_csv(value)

    @field_validator("workspaces", mode="before")
    @classmethod
    def _workspaces(cls, value: object) -> object:
        return _split_csv(value)

    @field_validator("workspaces")
    @classmethod
    def _unique_workspace_names(cls, value: list[Path]) -> list[Path]:
        names = [p.name for p in value]
        dupes = sorted({n for n in names if names.count(n) > 1})
        if dupes:
            raise ValueError(f"workspace names must be unique (duplicates: {dupes})")
        return value

    @field_validator("host")
    @classmethod
    def _loopback_only(cls, value: str) -> str:
        # Remote access arrives in Phase 11 through an authenticated private network gateway,
        # never by binding the execution service to a public interface.
        if value not in {"127.0.0.1", "::1", "localhost"}:
            raise ValueError("backend must bind to a loopback address")
        return value


def load_settings(store: SecretStore | None = None) -> Settings:
    """Environment first; for secrets missing from the environment, the OS credential store."""
    store = store or KeyringStore()
    overrides: dict[str, str] = {}
    if not os.environ.get("JARVIS_DATABASE_URL"):
        value = store.get("database_url")
        if value:
            overrides["database_url"] = value
    if not os.environ.get("JARVIS_AUDIT_KEY"):
        key = store.get(AUDIT_KEY_SECRET)
        if not key:
            key = secrets.token_urlsafe(32)
            try:
                store.set(AUDIT_KEY_SECRET, key)
                log.info("generated a new audit key and stored it in the OS credential store")
            except Exception:  # noqa: BLE001 - no usable credential store; create_app fails closed
                log.warning("no OS credential store available for the audit key")
                key = None
        if key:
            overrides["audit_key"] = key
    return Settings(**overrides)  # type: ignore[arg-type]


@lru_cache
def get_settings() -> Settings:
    return load_settings()
