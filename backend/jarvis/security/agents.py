"""Agent credentials: separate from, and weaker than, the human operator's session token.

The operator's session token is generated by the desktop shell and reaches only the webview
over Tauri IPC; it is the human-presence credential. Agents (Claude Code, Codex, model-driven
workers) never receive it: child processes get a scrubbed environment. Instead, each agent is
issued its own random token here, which authenticates as ``Principal.agent(<id>)``.

Agent tokens are per backend launch (held in memory as SHA-256 digests, never stored), can be
revoked individually, and are all revoked by the emergency stop. What an agent token may call
is restricted at the transport layer (see ``AGENT_ROUTES``); deciding approvals, resetting the
emergency stop and managing credentials are human-only.
"""

from __future__ import annotations

import hashlib
import hmac
import re
import secrets
import threading
from dataclasses import dataclass
from datetime import datetime

from jarvis.core.redaction import register_secret
from jarvis.core.time import utcnow
from jarvis.security.principal import Principal

TOKEN_PREFIX = "jat_"  # noqa: S105 - "JARVIS agent token" prefix, redacted everywhere
_AGENT_ID = re.compile(r"^[a-z0-9][a-z0-9_.\-]{0,63}$")
_RESERVED_IDS = frozenset({"operator", "jarvis", "system", "human"})

# (method, path regex) pairs an agent token may call. Everything else is human-only.
AGENT_ROUTES: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("POST", re.compile(r"^/api/v1/actions$")),
    ("GET", re.compile(r"^/api/v1/jobs/[0-9a-fA-F\-]{36}$")),
    ("GET", re.compile(r"^/api/v1/catalog$")),
    ("GET", re.compile(r"^/api/v1/health$")),
)


def agent_may_call(method: str, path: str) -> bool:
    return any(method == m and rx.match(path) for m, rx in AGENT_ROUTES)


class InvalidAgentId(ValueError):
    pass


class AgentAlreadyActive(ValueError):
    pass


@dataclass(frozen=True, slots=True)
class AgentCredential:
    agent_id: str
    created_at: datetime
    digest: str  # SHA-256 of the token; the token itself is never kept


def _digest(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


class AgentCredentials:
    def __init__(self) -> None:
        self._by_agent: dict[str, AgentCredential] = {}
        self._lock = threading.Lock()

    def issue(self, agent_id: str) -> tuple[AgentCredential, str]:
        """Create a credential and return it with the token. The token is shown exactly once."""
        if not _AGENT_ID.match(agent_id) or agent_id in _RESERVED_IDS:
            raise InvalidAgentId(
                "agent id must be 1-64 chars of a-z, 0-9, '.', '_' or '-' and not reserved"
            )
        token = TOKEN_PREFIX + secrets.token_urlsafe(32)
        cred = AgentCredential(agent_id, utcnow(), _digest(token))
        with self._lock:
            if agent_id in self._by_agent:
                raise AgentAlreadyActive(f"agent '{agent_id}' already has an active credential")
            self._by_agent[agent_id] = cred
        register_secret(token)
        return cred, token

    def authenticate(self, presented: str | None) -> Principal | None:
        if not presented or not presented.startswith(TOKEN_PREFIX):
            return None
        digest = _digest(presented)
        with self._lock:
            creds = list(self._by_agent.values())
        found: AgentCredential | None = None
        for cred in creds:  # compare every entry: no early exit on a match
            if hmac.compare_digest(cred.digest, digest):
                found = cred
        return Principal.agent(found.agent_id) if found else None

    def revoke(self, agent_id: str) -> bool:
        with self._lock:
            return self._by_agent.pop(agent_id, None) is not None

    def revoke_all(self) -> int:
        with self._lock:
            n = len(self._by_agent)
            self._by_agent.clear()
            return n

    def list(self) -> list[AgentCredential]:
        with self._lock:
            return sorted(self._by_agent.values(), key=lambda c: c.created_at)
